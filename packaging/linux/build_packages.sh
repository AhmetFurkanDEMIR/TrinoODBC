#!/bin/sh
# Builds the Trino ODBC driver on Linux and produces distributable packages with CPack:
# a .deb (when dpkg-deb is available), an .rpm (when rpmbuild is available) and always a .tar.gz.
#
#   build_packages.sh [options]
#
# Options:
#   --build-dir DIR        CMake build directory (default: build-linux-pkg)
#   --out DIR              where the packages are copied (default: dist/linux)
#   --generators LIST      CPack generators, ';'-separated (default: auto-detect DEB/RPM + TGZ)
#   --driver-manager DM    unixodbc (default) | iodbc
#   --prefix DIR           install prefix baked into the packages (default: /usr)
#   --libdir NAME          library directory relative to the prefix (default: distro convention)
#   --version V            package version (default: from CMakeLists.txt)
#   --jobs N               parallel build jobs (default: nproc)
#   --skip-tests           do not build/run the unit tests before packaging
#   --cmake-arg ARG        extra argument forwarded to cmake (repeatable)
#   -h, --help
#
# The deb/rpm maintainer scripts embed packaging/linux/register_driver.sh so that installing the
# package registers "Trino ODBC Driver" with unixODBC (odbcinst -i -d, or /etc/odbcinst.ini) and
# removing it unregisters the driver. Re-running the script is safe: the build directory is reused
# and packages are overwritten.
set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
BUILD_DIR="$ROOT/build-linux-pkg"
OUT_DIR="$ROOT/dist/linux"
GENERATORS=""
DRIVER_MANAGER=unixodbc
PREFIX=/usr
LIBDIR=""
VERSION=""
JOBS=""
SKIP_TESTS=0
EXTRA_CMAKE_ARGS=""

usage() { sed -n '2,23p' "$0" | sed 's/^# \{0,1\}//'; }
log() { printf '%s\n' "build_packages: $*"; }
die() { printf '%s\n' "build_packages: error: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --build-dir) shift; BUILD_DIR="$1" ;;
    --build-dir=*) BUILD_DIR="${1#*=}" ;;
    --out) shift; OUT_DIR="$1" ;;
    --out=*) OUT_DIR="${1#*=}" ;;
    --generators) shift; GENERATORS="$1" ;;
    --generators=*) GENERATORS="${1#*=}" ;;
    --driver-manager) shift; DRIVER_MANAGER="$1" ;;
    --driver-manager=*) DRIVER_MANAGER="${1#*=}" ;;
    --prefix) shift; PREFIX="$1" ;;
    --prefix=*) PREFIX="${1#*=}" ;;
    --libdir) shift; LIBDIR="$1" ;;
    --libdir=*) LIBDIR="${1#*=}" ;;
    --version) shift; VERSION="$1" ;;
    --version=*) VERSION="${1#*=}" ;;
    --jobs) shift; JOBS="$1" ;;
    --jobs=*) JOBS="${1#*=}" ;;
    --skip-tests) SKIP_TESTS=1 ;;
    --cmake-arg) shift; EXTRA_CMAKE_ARGS="$EXTRA_CMAKE_ARGS $1" ;;
    --cmake-arg=*) EXTRA_CMAKE_ARGS="$EXTRA_CMAKE_ARGS ${1#*=}" ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown option '$1' (see --help)" ;;
  esac
  shift
done

command -v cmake >/dev/null 2>&1 || die "cmake not found"
case "$BUILD_DIR" in /*) ;; *) BUILD_DIR="$ROOT/$BUILD_DIR" ;; esac
case "$OUT_DIR" in /*) ;; *) OUT_DIR="$ROOT/$OUT_DIR" ;; esac

# ---- defaults derived from the host ---------------------------------------------------------------
if [ -z "$VERSION" ]; then
  VERSION="$(sed -n 's/^project(trinoodbc VERSION \([0-9][0-9.]*\).*/\1/p' "$ROOT/CMakeLists.txt" | head -n 1)"
  [ -n "$VERSION" ] || VERSION=1.0.0
fi
if [ -z "$JOBS" ]; then
  JOBS="$(nproc 2>/dev/null || getconf _NPROCESSORS_ONLN 2>/dev/null || echo 2)"
fi
if [ -z "$LIBDIR" ]; then
  # Debian family: multiarch directory; RPM family on 64-bit: lib64; everything else: lib.
  if command -v dpkg-architecture >/dev/null 2>&1; then
    LIBDIR="lib/$(dpkg-architecture -qDEB_HOST_MULTIARCH 2>/dev/null || echo x86_64-linux-gnu)"
  elif command -v rpm >/dev/null 2>&1 && [ -d "$PREFIX/lib64" ]; then
    LIBDIR=lib64
  else
    LIBDIR=lib
  fi
fi
if [ -z "$GENERATORS" ]; then
  GENERATORS="TGZ"
  command -v dpkg-deb >/dev/null 2>&1 && GENERATORS="$GENERATORS;DEB"
  command -v rpmbuild >/dev/null 2>&1 && GENERATORS="$GENERATORS;RPM"
fi
DRIVER_INSTALL_PATH="$PREFIX/$LIBDIR/libtrinoodbc.so"
log "version $VERSION, driver manager $DRIVER_MANAGER, prefix $PREFIX, libdir $LIBDIR, generators $GENERATORS"

# ---- maintainer scripts (embed register_driver.sh) ------------------------------------------------
# dpkg calls postinst with "configure" and prerm with "remove"/"upgrade"; rpm calls %post with the
# install count (1 = first install, 2 = upgrade) and %preun with the remaining count (0 = removal).
# Registration is idempotent, so only a real removal unregisters (an upgrade re-registers).
SCRIPTS_DIR="$BUILD_DIR/pkgscripts"
mkdir -p "$SCRIPTS_DIR"
REGISTER_SCRIPT="$SCRIPT_DIR/register_driver.sh"
[ -f "$REGISTER_SCRIPT" ] || die "$REGISTER_SCRIPT is missing"

write_maintainer_script() {  # OUT_FILE MODE_FLAG CASE_PATTERN
  {
    printf '#!/bin/sh\n'
    printf '# Generated by packaging/linux/build_packages.sh -- embeds packaging/linux/register_driver.sh.\n'
    printf 'set -e\n'
    printf 'trino_odbc_driver_setup() {\n'
    sed -e '1{/^#!/d;}' "$REGISTER_SCRIPT"
    printf '}\n'
    printf 'case "${1:-}" in\n'
    printf '  %s)\n' "$3"
    printf '    ( trino_odbc_driver_setup %s "%s" ) || echo "trinoodbc: driver registration step failed; run %s manually" >&2 ;;\n' \
      "$2" "$DRIVER_INSTALL_PATH" "register_driver.sh $2 $DRIVER_INSTALL_PATH"
    printf 'esac\nexit 0\n'
  } > "$1"
  chmod 755 "$1"
  sh -n "$1" || die "generated maintainer script $1 does not parse"
}
write_maintainer_script "$SCRIPTS_DIR/postinst" "--register" "configure|1|2"
write_maintainer_script "$SCRIPTS_DIR/prerm" "--unregister" "remove|0"

# ---- configure + build ------------------------------------------------------------------------------
BUILD_TESTS=ON
[ "$SKIP_TESTS" = 1 ] && BUILD_TESTS=OFF
# shellcheck disable=SC2086  # EXTRA_CMAKE_ARGS is intentionally word-split
cmake -S "$ROOT" -B "$BUILD_DIR" \
  -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_INSTALL_PREFIX="$PREFIX" \
  -DCMAKE_INSTALL_LIBDIR="$LIBDIR" \
  -DCPACK_PACKAGING_INSTALL_PREFIX="$PREFIX" \
  -DTRINO_ODBC_DRIVER_MANAGER="$DRIVER_MANAGER" \
  -DTRINO_ODBC_BUILD_TESTS="$BUILD_TESTS" \
  -DTRINO_ODBC_INSTALL_ODBCINST=OFF \
  -DCPACK_PACKAGE_VERSION="$VERSION" \
  -DCPACK_PACKAGE_FILE_NAME="trino-odbc-$VERSION-linux-$(uname -m)" \
  -DCPACK_DEBIAN_PACKAGE_CONTROL_EXTRA="$SCRIPTS_DIR/postinst;$SCRIPTS_DIR/prerm" \
  -DCPACK_DEBIAN_FILE_NAME=DEB-DEFAULT \
  -DCPACK_DEBIAN_PACKAGE_SECTION=database \
  -DCPACK_DEBIAN_PACKAGE_PRIORITY=optional \
  -DCPACK_RPM_POST_INSTALL_SCRIPT_FILE="$SCRIPTS_DIR/postinst" \
  -DCPACK_RPM_PRE_UNINSTALL_SCRIPT_FILE="$SCRIPTS_DIR/prerm" \
  -DCPACK_RPM_FILE_NAME=RPM-DEFAULT \
  -DCPACK_RPM_PACKAGE_LICENSE="Apache-2.0" \
  -DCPACK_RPM_PACKAGE_GROUP="Applications/Databases" \
  -DCPACK_RPM_EXCLUDE_FROM_AUTO_FILELIST_ADDITION="/usr/share/doc;$PREFIX/$LIBDIR;$PREFIX/share" \
  $EXTRA_CMAKE_ARGS
cmake --build "$BUILD_DIR" --config Release --parallel "$JOBS"

if [ "$SKIP_TESTS" != 1 ] && [ -x "$BUILD_DIR/tests/trino_odbc_unit_tests" ]; then
  log "running unit tests"
  "$BUILD_DIR/tests/trino_odbc_unit_tests" || die "unit tests failed; not packaging"
fi

# ---- package ----------------------------------------------------------------------------------------
mkdir -p "$OUT_DIR"
old_ifs="$IFS"; IFS=';'
for gen in $GENERATORS; do
  IFS="$old_ifs"
  [ -n "$gen" ] || continue
  log "cpack -G $gen"
  (cd "$BUILD_DIR" && cpack -G "$gen" -C Release) || die "cpack -G $gen failed"
  IFS=';'
done
IFS="$old_ifs"

found=0
for f in "$BUILD_DIR"/*.deb "$BUILD_DIR"/*.rpm "$BUILD_DIR"/*.tar.gz; do
  [ -f "$f" ] || continue
  cp -f "$f" "$OUT_DIR/"
  log "package: $OUT_DIR/$(basename "$f")"
  found=1
done
[ "$found" = 1 ] || die "no package was produced"
log "done"
